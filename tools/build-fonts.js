#!/usr/bin/env node
// Builds assets/css/fonts.css: the app's two typefaces embedded as data: URIs,
// so they work identically on GitHub Pages and from file:// (where the browser
// refuses font files by CORS) and the app makes no third-party request.
//
// Usage: node tools/build-fonts.js   (development only; the output is versioned)
//
// Plus Jakarta Sans (headings and reading text) and Outfit (interface), both
// SIL Open Font License 1.1, variable weight, Latin subset — which covers
// Spanish in full (ñ, á, ü, º, ª, «», “”, –, €).

"use strict";
const fs = require("fs");
const path = require("path");

const FAMILIES = [
  { family: "Plus Jakarta Sans", axis: "ital,wght@0,400..800;1,400..800" },
  { family: "Outfit", axis: "wght@300..700" },
];
// A current browser's user agent: Google Fonts then serves woff2.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36";
const OUT = path.join(__dirname, "..", "assets", "css", "fonts.css");

(async () => {
  let css = `/* Generated by tools/build-fonts.js — do not edit.\n * Plus Jakarta Sans and Outfit, SIL Open Font License 1.1 (https://openfontlicense.org).\n * Latin subset, variable weight, embedded so that no font is fetched from a third party. */\n`;
  let bytes = 0;
  for (const { family, axis } of FAMILIES) {
    const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, "+")}:${axis}&display=swap`;
    const sheet = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
    // Keep only the "latin" blocks (Google labels each block with a comment).
    for (const block of sheet.split(/(?=\/\* )/)) {
      if (!/^\/\* latin \*\//.test(block)) continue;
      const src = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
      const font = Buffer.from(await (await fetch(src)).arrayBuffer());
      bytes += font.length;
      css += block
        .replace(/^\/\* latin \*\/\s*/, "")
        .replace(/url\(https:[^)]+\)/, `url(data:font/woff2;base64,${font.toString("base64")})`)
        .replace(/font-display:\s*swap;/, "font-display: swap;");
    }
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, css);
  console.log(`${path.relative(process.cwd(), OUT)}: ${(bytes / 1024).toFixed(0)} KB de fuentes, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB de CSS`);
})().catch((err) => {
  console.error(err.message);
  process.exitCode = 1;
});
