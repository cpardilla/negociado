#!/usr/bin/env node
// Builds 404.html: GitHub Pages serves it for any address that does not exist. The addresses of the
// old app (one HTML file per resource) are looked up in a table and redirected to their new place;
// an address with no equivalent gets a notice to update the bookmark (owner's decision 8).
//
// Usage: node tools/build-404.js
// The page is self-contained (no stylesheet or script files): it may be served at any depth.

"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const catalogo = JSON.parse(fs.readFileSync(path.join(ROOT, "sources", "actual", "catalogo.json"), "utf8"));
const { recursos } = JSON.parse(fs.readFileSync(path.join(__dirname, "migracion.json"), "utf8"));

/** Old path → new route ("" when the resource has no equivalent). */
function route(item) {
  if (item.tipo === "indice") return `#/ley/${item.id.slice(2)}`;
  if (item.tipo === "legislacion") return `#/ley/${item.id.slice(2)}/mapa`;
  const m = recursos[item.id];
  if (item.tipo === "esquema") return m.id ? `#/esquema/${m.id}` : "";
  return `#/guia/${recursos[m.esquema].id}`;
}
// Keys folded (no accents, lower case, single spaces) so that any encoding of the old name matches.
const fold = (s) => s.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase().replace(/\s+/g, " ").trim();
const table = Object.fromEntries(catalogo.map((item) => [fold(item.ruta), route(item)]));
const folders = [...new Set(catalogo.map((item) => fold(item.ruta.split("/")[0])))];

const html = `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Página no encontrada · Negociado</title>
<meta name="robots" content="noindex">
<style>
  :root { color-scheme: light dark; --bg: light-dark(#f7f6f2, #0d1220); --text: light-dark(#0f172a, #e8eaf0); --muted: light-dark(#475569, #b4bccb); --link: light-dark(#2e4daa, #9fb4f2); --line: #c8a96e; }
  body { margin: 0; min-height: 100vh; display: grid; place-items: center; background: var(--bg); color: var(--text); font: 16px/1.6 system-ui, "Segoe UI", sans-serif; }
  main { max-width: 34rem; padding: 2rem 1.5rem; border-top: 3px solid var(--line); }
  h1 { font-size: 1.4rem; margin: 0 0 .5rem; }
  p { color: var(--muted); margin: .5rem 0; }
  a { color: var(--link); }
</style>
</head>
<body>
<main id="msg" hidden>
  <h1>Esta dirección ya no existe</h1>
  <p>Negociado se ha renovado y sus recursos tienen direcciones nuevas. Si llegaste aquí desde un favorito, actualízalo con la nueva dirección.</p>
  <p><a id="home" href="./">Ir al inicio de Negociado</a></p>
</main>
<script>
  // Generated by tools/build-404.js — the old addresses of the app and their new place.
  (function () {
    var TABLE = ${JSON.stringify(table)};
    var FOLDERS = ${JSON.stringify(folders)};
    function fold(s) { return s.normalize("NFD").replace(/\\p{M}/gu, "").toLowerCase().replace(/\\s+/g, " ").trim(); }
    var path = location.pathname;
    try { path = decodeURIComponent(path); } catch (e) { /* malformed escape: compared as it is */ }
    var parts = path.split("/");
    var at = -1;
    for (var i = 0; i < parts.length && at < 0; i++) if (FOLDERS.indexOf(fold(parts[i])) >= 0) at = i;
    // The site's base: what precedes the old folder (e.g. "/negociado/"), or the first segment on github.io.
    var base = at >= 0 ? parts.slice(0, at).join("/") + "/" : (/\\.github\\.io$/.test(location.hostname) && parts[1] ? "/" + parts[1] + "/" : "/");
    var target = at >= 0 ? TABLE[fold(parts.slice(at).join("/"))] : undefined;
    if (target) { location.replace(base + target); return; }
    document.getElementById("home").href = base;
    document.getElementById("msg").hidden = false;
  })();
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(ROOT, "404.html"), html);
const redirected = Object.values(table).filter(Boolean).length;
console.log(`404.html: ${redirected} direcciones antiguas redirigidas, ${Object.keys(table).length - redirected} con aviso (sin equivalente)`);
